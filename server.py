MIRROR_MARK = "<!-- generated by Pulse: edit this note in Pulse; changes made here are overwritten -->"


def write_notes_mirror():
    """Optional read-only Markdown copy of non-private notes (e.g. an Obsidian vault folder)."""
    if not CONFIG.get("notes_mirror_dir"):
        return
    folder = Path(os.path.expanduser(CONFIG["notes_mirror_dir"]))
    folder.mkdir(parents=True, exist_ok=True)
    con = db()
    try:
        notes = con.execute("SELECT * FROM notes WHERE private=0").fetchall()
    finally:
        con.close()
    keep = set()
    for n in notes:
        slug = re.sub(r"[^a-z0-9]+", "-", (n["title"] or n["body"][:40]).lower()).strip("-")[:50] or "note"
        name = f"{n['id']:05d}-{slug}.md"
        keep.add(name)
        tags = json.loads(n["tags"] or "[]")
        fm = ["---", f"pulse_id: {n['id']}", f"title: {json.dumps(n['title'])}",
              f"created: {datetime.fromtimestamp(n['created_at'], TZ).isoformat()}",
              f"updated: {datetime.fromtimestamp(n['updated_at'], TZ).isoformat()}",
              f"tags: {json.dumps(tags)}"] + ([f"project: {n['project']}"] if n["project"] else []) + ["---", MIRROR_MARK, ""]
        content = "\n".join(fm) + (f"# {n['title']}\n\n" if n["title"] else "") + n["body"].strip() + "\n"
        f = folder / name
        if not f.exists() or f.read_text() != content:
            tmp = f.with_suffix(".tmp")
            tmp.write_text(content)
            tmp.replace(f)
    for f in folder.glob("*.md"):
        if f.name not in keep and MIRROR_MARK in f.read_text(errors="ignore"):
            f.unlink()


