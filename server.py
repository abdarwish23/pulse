def detect_timezone():
    tz = os.environ.get("TZ", "")
    if not tz and os.path.islink("/etc/localtime"):
        tz = os.path.realpath("/etc/localtime").split("zoneinfo/")[-1]
    try:
        ZoneInfo(tz)
        return tz
    except Exception:
        return "UTC"


def load_config():
    cfg = json.loads(CONFIG_PATH.read_text()) if CONFIG_PATH.exists() else {}
    cfg.setdefault("host", "127.0.0.1")
    cfg.setdefault("port", 4100)
    cfg.setdefault("timezone", "")            # empty = server's timezone
    cfg.setdefault("password_hash", "")       # set with: python3 server.py set-password
    cfg.setdefault("secret", "")              # signs session cookies (generated by init)
    cfg.setdefault("trust_localhost", False)  # direct requests from 127.0.0.1 act as the owner
    cfg.setdefault("access_team", "")         # optional Cloudflare Access
    cfg.setdefault("access_aud", "")
    cfg.setdefault("tokens", {})              # agent tokens: {"<token>": "<name>"}
    cfg.setdefault("public_url", "")          # used for links in Telegram messages
    # telegram: {"enabled", "chat_id", "bot_token" | "bot_token_file", "notify_user_actions"}
    cfg.setdefault("telegram", {})
    cfg.setdefault("github_poll_seconds", 300)
    cfg.setdefault("memory_backend", "builtin")  # or "bridge" (external memory.mjs via memory_bridge.mjs)
    cfg.setdefault("notes_mirror_dir", "")    # optional read-only Markdown copy of notes (e.g. for Obsidian)
    return cfg


