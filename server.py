# ---------- passwords and sessions ----------
SESSION_DAYS = 30
_login_fails = {}


def hash_password(pw, iterations=310_000):
    salt = os.urandom(16).hex()
    dk = hashlib.pbkdf2_hmac("sha256", pw.encode(), bytes.fromhex(salt), iterations).hex()
    return f"pbkdf2_sha256${iterations}${salt}${dk}"


def check_password(pw, stored):
    try:
        _, it, salt, dk = stored.split("$")
        return hmac.compare_digest(hashlib.pbkdf2_hmac("sha256", pw.encode(), bytes.fromhex(salt), int(it)).hex(), dk)
    except ValueError:
        return False


def _sign(msg):
    need(CONFIG["secret"], "server secret missing; run: python3 server.py init", 500)
    return hmac.new(CONFIG["secret"].encode(), msg.encode(), hashlib.sha256).hexdigest()


def make_session():
    exp = str(now() + SESSION_DAYS * 86400)
    # binding to the password hash means changing the password signs everyone out
    return f"{exp}.{_sign(exp + CONFIG['password_hash'])}"


def session_valid(value):
    exp, _, sig = value.partition(".")
    return exp.isdigit() and int(exp) > now() and hmac.compare_digest(sig, _sign(exp + CONFIG["password_hash"]))


def login_allowed(ip):
    recent = [t for t in _login_fails.get(ip, []) if t > now() - 900]
    _login_fails[ip] = recent
    return len(recent) < 10


def login_failed(ip):
    _login_fails.setdefault(ip, []).append(now())


