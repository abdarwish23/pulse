_mem_lock = threading.Lock()


def memory_call(op, args=None):
    bridge = ROOT / "memory_bridge.mjs"
    module = os.path.expanduser(CONFIG.get("memory_module") or "")
    with _mem_lock:
        r = subprocess.run([CONFIG.get("node_bin") or "/usr/bin/node", str(bridge), op, module],
                           input=json.dumps(args or {}), capture_output=True, text=True, timeout=60)
    if r.returncode != 0:
        raise ApiError(502, f"memory: {(r.stderr or r.stdout).strip()[:300]}")
    return json.loads(r.stdout)


LOOKS_SECRET = re.compile(r"sk-[A-Za-z0-9_-]{16,}|[A-Za-z0-9+/_-]{40,}|password\s*[:=]", re.I)


def iso(ts):
    return datetime.fromtimestamp(ts, timezone.utc).isoformat(timespec="seconds")


def memory_builtin(con, op, a):
    """Long-term memory in SQLite: entities (people, projects, preferences...) with facts."""
    norm = lambda x: str(x or "").strip().lower()
    ent = lambda name: con.execute("SELECT * FROM memory_entities WHERE name=?", (str(name).strip(),)).fetchone()
    facts = lambda eid: con.execute("SELECT * FROM memory_facts WHERE entity_id=? ORDER BY id", (eid,)).fetchall()
    if op == "list":
        return {"entities": [{"name": e["name"], "type": e["type"], "updated": iso(e["updated_at"]),
                              "facts": [{"id": f["id"], "text": f["text"], "added": iso(f["added_at"]), "updated": iso(f["updated_at"])}
                                        for f in facts(e["id"])]}
                             for e in con.execute("SELECT * FROM memory_entities ORDER BY name COLLATE NOCASE")]}
    if op == "remember":
        name = clean_str(a.get("entity", ""), "entity", 120)
        need(name, "entity required")
        need(isinstance(a.get("facts"), list) and a["facts"], "facts must be a non-empty list")
        e = ent(name)
        if not e:
            con.execute("INSERT INTO memory_entities(name,type,updated_at) VALUES(?,?,?)", (name, a.get("type") or "general", now()))
            e = ent(name)
        known = {norm(f["text"]) for f in facts(e["id"])}
        added = []
        for f in a["facts"]:
            text = str(f).strip()[:1000]
            if text and norm(text) not in known and not LOOKS_SECRET.search(text):
                con.execute("INSERT INTO memory_facts(entity_id,text,added_at,updated_at) VALUES(?,?,?,?)", (e["id"], text, now(), now()))
                known.add(norm(text)); added.append(text)
        if added:
            con.execute("UPDATE memory_entities SET updated_at=? WHERE id=?", (now(), e["id"]))
        return {"message": f"Remembered {len(added)} fact(s) about {e['name']}: {'; '.join(added)}" if added
                else f"{e['name']} already has those facts (secrets are never stored)."}
    if op == "recall":
        q = norm(a.get("query"))
        hits = [e for e in con.execute("SELECT * FROM memory_entities ORDER BY name COLLATE NOCASE")
                if q in norm(e["name"]) or q in norm(e["type"]) or any(q in norm(f["text"]) for f in facts(e["id"]))]
        if not hits:
            return {"message": f"Nothing remembered about \"{a.get('query')}\"."}
        return {"message": "\n\n".join(f"{e['name']} ({e['type']})\n" + ("\n".join(
            f"- {f['text']} (updated {iso(f['updated_at'])[:10]})" for f in facts(e["id"])) or "- (no facts)") for e in hits)}
    e = ent(a.get("entity", ""))
    if not e:
        return {"message": f"Nothing remembered about \"{a.get('entity')}\"."}
    if op == "update":
        need(a.get("new_text"), "new_text required")
        if LOOKS_SECRET.search(a["new_text"]):
            return {"message": "Refused: looks like a secret."}
        m = [f for f in facts(e["id"]) if norm(a.get("old_text")) in norm(f["text"])]
        if len(m) != 1:
            return {"message": f"\"{a.get('old_text')}\" matches {len(m)} facts about {e['name']}" +
                    (": " + " | ".join(f["text"] for f in m) if m else ".")}
        con.execute("UPDATE memory_facts SET text=?, updated_at=? WHERE id=?", (a["new_text"].strip()[:1000], now(), m[0]["id"]))
        con.execute("UPDATE memory_entities SET updated_at=? WHERE id=?", (now(), e["id"]))
        return {"message": f"Updated fact about {e['name']}: \"{a['new_text'].strip()}\"."}
    if op == "forget":
        if not a.get("fact"):
            con.execute("DELETE FROM memory_entities WHERE id=?", (e["id"],))
            return {"message": f"Forgot everything about {e['name']}."}
        m = [f["id"] for f in facts(e["id"]) if norm(a["fact"]) in norm(f["text"])]
        con.executemany("DELETE FROM memory_facts WHERE id=?", [(i,) for i in m])
        return {"message": f"Forgot {len(m)} fact(s) about {e['name']}." if m else f"No fact about {e['name']} matches \"{a['fact']}\"."}
    raise ApiError(404, "unknown memory operation")


