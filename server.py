class Handler(BaseHTTPRequestHandler):
    server_version = "Pulse/1"

    def log_message(self, fmt, *args):
        sys.stderr.write("%s %s\n" % (self.command, self.path))

    # identity: returns (role, name) or raises
    def client_ip(self):
        return (self.headers.get("Cf-Connecting-Ip") or self.headers.get("X-Forwarded-For", "").split(",")[0].strip()
                or self.client_address[0])

    def identity(self, write=False):
        """Returns (role, name): ("agent", name) for token holders, ("user", name) for the owner. Else 401."""
        auth = self.headers.get("Authorization", "")
        tok = auth[7:].strip() if auth.startswith("Bearer ") else ""
        if tok:
            name = next((n for t, n in CONFIG["tokens"].items() if hmac.compare_digest(t, tok)), None)
            need(name, "invalid token", 401)
            # token holders may name the specific agent (codex, pi, claude...) for the timeline
            alias = re.sub(r"[^a-z0-9_.-]", "", self.headers.get("X-Pulse-Agent", "").lower())[:24]
            return ("agent", alias or name)
        cookies = self.headers.get("Cookie", "")
        if CONFIG["access_team"] and CONFIG["access_aud"]:
            jwt = self.headers.get("Cf-Access-Jwt-Assertion", "")
            if not jwt:
                m = re.search(r"CF_Authorization=([^;]+)", cookies)
                jwt = m.group(1) if m else ""
            claims = verify_access_jwt(jwt, CONFIG["access_team"], CONFIG["access_aud"]) if jwt else None
            if claims:
                return ("user", claims.get("email", "owner").split("@")[0])
        m = re.search(r"pulse_session=([^;]+)", cookies)
        if m and CONFIG["password_hash"] and session_valid(m.group(1)):
            return ("user", "owner")
        proxied = any(self.headers.get(h) for h in ("X-Forwarded-For", "Forwarded", "X-Real-Ip", "Cf-Ray", "Cf-Connecting-Ip"))
        if CONFIG["trust_localhost"] and not proxied and self.client_address[0] in ("127.0.0.1", "::1"):
            return ("user", "owner")
        raise ApiError(401, "login required")

    def auth_route(self, method, path):
        """Public endpoints: login options, sign in, sign out."""
        if path == "/api/auth" and method == "GET":
            return self.send_json(200, {"password": bool(CONFIG["password_hash"]),
                                        "cloudflare": bool(CONFIG["access_team"] and CONFIG["access_aud"])})
        if path == "/api/login" and method == "POST":
            ip = self.client_ip()
            need(login_allowed(ip), "too many attempts, try again in 15 minutes", 429)
            pw = self.body().get("password", "")
            if not (CONFIG["password_hash"] and isinstance(pw, str) and check_password(pw, CONFIG["password_hash"])):
                login_failed(ip)
                raise ApiError(401, "wrong password")
            return self.send_json(200, {"ok": True}, cookie=make_session())
        if path == "/api/logout" and method == "POST":
            return self.send_json(200, {"ok": True}, cookie="")
        raise ApiError(404, "not found")

    def send_json(self, code, obj, cookie=None):
        body = json.dumps(obj).encode()
        self.send_response(code)
        if cookie is not None:
            secure = "; Secure" if (CONFIG["public_url"].startswith("https") or
                                    self.headers.get("X-Forwarded-Proto") == "https") else ""
            age = SESSION_DAYS * 86400 if cookie else 0
            self.send_header("Set-Cookie", f"pulse_session={cookie}; Path=/; HttpOnly; SameSite=Lax; Max-Age={age}{secure}")
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def body(self):
        n = int(self.headers.get("Content-Length") or 0)
        need(n <= MAX_BODY, "body too large", 413)
        if not n:
            return {}
        try:
            data = json.loads(self.rfile.read(n))
        except ValueError:
            raise ApiError(400, "invalid JSON")
        need(isinstance(data, dict), "JSON object expected")
        return data

    def serve_static(self, path):
        name = {"/": "index.html"}.get(path, path.lstrip("/"))
        f = (STATIC / name).resolve()
        if not str(f).startswith(str(STATIC.resolve())) or not f.is_file():
            return self.send_json(404, {"error": "not found"})
        ctype = {".html": "text/html; charset=utf-8", ".json": "application/manifest+json",
                 ".svg": "image/svg+xml", ".js": "text/javascript", ".css": "text/css"}.get(f.suffix, "application/octet-stream")
        data = f.read_bytes()
        self.send_response(200)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-cache")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Content-Security-Policy",
                         "default-src 'self'; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline'; img-src 'self' data:")
        self.end_headers()
        self.wfile.write(data)

    def handle_any(self, method):
        url = urlparse(self.path)
        path = url.path.rstrip("/") or "/"
        try:
            if not path.startswith("/api"):
                need(method == "GET", "method not allowed", 405)
                return self.serve_static(path)  # the app shell holds no data; every /api call is authenticated
            if path in ("/api/auth", "/api/login", "/api/logout"):
                return self.auth_route(method, path)
            role, who = self.identity()
            con = db()
            try:
                with con:
                    code, out = self.route(con, method, path, parse_qs(url.query), who, role)
                flush_deferred(True)
            except Exception:
                flush_deferred(False)
                raise
            finally:
                con.close()
            self.send_json(code, out)
        except ApiError as e:
            self.send_json(e.code, {"error": e.msg})
        except sqlite3.IntegrityError as e:
            self.send_json(409, {"error": str(e)})
        except Exception as e:  # pragma: no cover
            sys.stderr.write(f"error: {e!r}\n")
            self.send_json(500, {"error": "internal error"})

    def do_GET(self): self.handle_any("GET")
    def do_POST(self): self.handle_any("POST")
    def do_PATCH(self): self.handle_any("PATCH")
    def do_DELETE(self): self.handle_any("DELETE")

