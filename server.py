                ts = m["done_at"] or now()
                con.execute("INSERT INTO cards(project,title,col,position,created_by,created_at,updated_at,done_at)"
                            " VALUES(?,?,?,?,?,?,?,?)", (m["project"], m["title"], col, pos[key], "migration", ts, ts, m["done_at"]))
