REL_RE = re.compile(r"^in\s+(\d+)\s*(m|min|mins|minutes?|h|hrs?|hours?|d|days?)$", re.I)
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
TIME_RE = re.compile(r"^\d{1,2}:\d{2}$")


def local_now():
    return datetime.now(TZ)


def fmt_local(ts):
    return datetime.fromtimestamp(ts, TZ).strftime("%a %d %b %H:%M")


def today_str():
    return local_now().strftime("%Y-%m-%d")


def parse_when(v):
    """Local-time parser shared by API and MCP. Accepts epoch seconds, 'in 30m' / 'in 2h' / 'in 1d',
    'HH:MM' (next occurrence), 'YYYY-MM-DD' (09:00), 'YYYY-MM-DD HH:MM' (local) or ISO 8601 with offset."""
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return int(v)
    s = str(v or "").strip()
    m = REL_RE.match(s)
    if m:
        return now() + int(m[1]) * {"m": 60, "h": 3600, "d": 86400}[m[2][0].lower()]
    low = s.lower()
    if low.startswith(("today", "tomorrow")):
        rest = s.split(None, 1)[1] if " " in s else "09:00"
        d = local_now() + timedelta(days=1 if low.startswith("tomorrow") else 0)
        s = f"{d:%Y-%m-%d} {rest}"
    if TIME_RE.match(s):
        h, mi = map(int, s.split(":"))
        d = local_now().replace(hour=h, minute=mi, second=0, microsecond=0)
        if d.timestamp() <= time.time():
            d += timedelta(days=1)
        return int(d.timestamp())
    if DATE_RE.match(s):
        s += " 09:00"
    try:
        d = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        raise ApiError(400, f"cannot understand time '{v}'. Use 'YYYY-MM-DD HH:MM' (local, {TZ.key}), 'HH:MM', "
                            "'tomorrow 09:00', 'in 30m', or ISO 8601")
    if d.tzinfo is None:
        d = d.replace(tzinfo=TZ)
    return int(d.timestamp())


def parse_due(v):
    """Due for todos -> (date 'YYYY-MM-DD' | None, time 'HH:MM' | None)."""
    s = str(v or "").strip()
    if not s:
        return None, None
    low = s.lower()
    if low in ("today", "tomorrow"):
        return (local_now() + timedelta(days=low == "tomorrow")).strftime("%Y-%m-%d"), None
    if DATE_RE.match(s):
        return s, None
    d = datetime.fromtimestamp(parse_when(s), TZ)
    return d.strftime("%Y-%m-%d"), d.strftime("%H:%M")


def next_occurrence(ts, repeat):
    d = datetime.fromtimestamp(ts, TZ)
    day = d.day
    while d.timestamp() <= time.time():
        if repeat == "daily":
            d += timedelta(days=1)
        elif repeat == "weekdays":
            d += timedelta(days=1)
            while d.weekday() >= 5:
                d += timedelta(days=1)
        elif repeat == "weekly":
            d += timedelta(days=7)
        elif repeat == "monthly":
            y, mo = (d.year + (d.month == 12), d.month % 12 + 1)
            d = d.replace(year=y, month=mo, day=min(day, calendar.monthrange(y, mo)[1]))
        else:
            raise ValueError(repeat)
    return int(d.timestamp())


