            con.execute("ALTER TABLE projects ADD COLUMN github_repo TEXT NOT NULL DEFAULT ''")
            con.execute("ALTER TABLE projects ADD COLUMN gh_synced_at INTEGER NOT NULL DEFAULT 0")
