def create_reminder(con, b, who):
    text = clean_str(b.get("text", ""), "text", 1000)
    need(text, "text required")
    if b.get("in_minutes") is not None:
        at = now() + int(float(b["in_minutes"]) * 60)
    else:
        need(b.get("at") not in (None, ""), "at (or in_minutes) required")
        at = parse_when(b["at"])
    repeat = b.get("repeat") or ""
    need(repeat in REPEATS, f"repeat must be one of {', '.join(r for r in REPEATS if r)}")
    need(at > now() - 60 or repeat, "that time is in the past")
    if repeat and at <= now():
        at = next_occurrence(at, repeat)
    todo_id = b.get("todo_id")
    if todo_id:
        need(con.execute("SELECT 1 FROM todos WHERE id=?", (todo_id,)).fetchone(), "todo not found")
    rid = con.execute("INSERT INTO reminders(text,at,repeat,todo_id,project,private,created_by,created_at)"
                      " VALUES(?,?,?,?,?,?,?,?)",
                      (text, at, repeat, todo_id, check_project(con, b.get("project")), as_bool(b.get("private")),
                       who, now())).lastrowid
    return reminder_out(con.execute("SELECT * FROM reminders WHERE id=?", (rid,)).fetchone())


