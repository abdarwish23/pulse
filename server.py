#!/usr/bin/env python3
"""Pulse: a simple, self-hosted personal hub for you and your AI agents.

Projects (kanban), notes, todos, reminders, notifications and long-term memory
in one Python file with zero dependencies (standard library + SQLite).

  python3 server.py init           create config.json, an agent token and a password
  python3 server.py                run the server (default http://127.0.0.1:4100)
  python3 server.py set-password   change the web password
  python3 server.py add-token NAME create another agent token

Who can do what
- Agents authenticate with `Authorization: Bearer <token>` (tokens in config.json).
- You sign in to the web app with a password (signed session cookie), or through
  Cloudflare Access (JWT verified), or - only on a trusted machine - with
  `trust_localhost` for requests that come straight from 127.0.0.1.
- Everything else gets 401. Items marked private are never returned to agents.
"""
